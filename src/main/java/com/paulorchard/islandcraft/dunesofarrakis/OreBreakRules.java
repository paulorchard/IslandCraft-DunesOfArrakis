package com.paulorchard.islandcraft.dunesofarrakis;

import com.hypixel.hytale.server.core.asset.type.blocktype.config.BlockBreakingDropType;
import com.hypixel.hytale.server.core.asset.type.blocktype.config.BlockType;
import com.hypixel.hytale.server.core.asset.type.item.config.Item;
import com.hypixel.hytale.server.core.asset.type.item.config.ItemTool;
import com.hypixel.hytale.server.core.asset.type.item.config.ItemToolSpec;
import com.hypixel.hytale.server.core.inventory.ItemStack;
import com.hypixel.hytale.server.core.universe.world.World;
import com.hypixel.hytale.server.core.universe.world.worldgen.provider.IWorldGenProvider;

import java.util.Map;
import java.util.Objects;
import java.util.Set;

/**
 * Which blocks are worn down by mining, in which worlds, and how many free breaks each gets. The one place to add more ores later.
 *
 * <p>An ore block in a Dunes of Arrakis world gives one ore for each of its first {@link #FREE_BREAKS} breaks and stays where it is;
 * the next break is the engine's own and gives the full normal drop.
 */
final class OreBreakRules {

    /** How many times a block is mined without breaking. The next break breaks it. */
    static final int FREE_BREAKS = 5;

    /** The listed ore blocks, each with the item one free break gives. */
    static final Map<String, String> ORE_OF_BLOCK = Map.of(
            "Ore_Copper_Sandstone", "Ore_Copper",
            "Ore_Iron_Sandstone", "Ore_Iron",
            "Ore_Silver_Sandstone", "Ore_Silver",
            "Ore_Gold_Sandstone", "Ore_Gold",
            "Ore_Thorium_Sandstone", "Ore_Thorium");

    /** Items that are never given by a free break (the rock the ore is embedded in). */
    private static final Set<String> NOT_ORE_PREFIXES = Set.of("Rock_");

    private OreBreakRules() {
    }

    static boolean isListed(String blockId) {
        return blockId != null && ORE_OF_BLOCK.containsKey(blockId);
    }

    /** True for the worlds this applies to: those generated by Dunes_of_Arrakis. */
    static boolean appliesTo(World world) {
        return world != null && appliesTo(world.getWorldConfig().getWorldGenProvider());
    }

    static boolean appliesTo(IWorldGenProvider provider) {
        return provider instanceof DunesOfArrakisWorldGenProvider;
    }

    /** Whether a drop of this item belongs in a free break. */
    static boolean isOreItem(String itemId) {
        if (itemId == null) {
            return false;
        }
        for (String prefix : NOT_ORE_PREFIXES) {
            if (itemId.startsWith(prefix)) {
                return false;
            }
        }
        return true;
    }

    /**
     * Whether the held item is a tool that can mine this block: it has a tool spec of the block's gather type and at least the block's
     * quality. This is the engine's own test (BlockHarvestUtils.getSpecPowerDamageBlock); a hit with anything else still hurts the block a
     * little, as bare hands do, and is left alone by this rule.
     */
    static boolean toolCanMine(ItemStack held, BlockType block) {
        if (held == null || block == null || block.getGathering() == null) {
            return false;
        }
        BlockBreakingDropType breaking = block.getGathering().getBreaking();
        Item item = held.getItem();
        ItemTool tool = item == null ? null : item.getTool();
        if (breaking == null || breaking.getGatherType() == null || tool == null || tool.getSpecs() == null) {
            return false;
        }
        for (ItemToolSpec spec : tool.getSpecs()) {
            if (Objects.equals(spec.getGatherType(), breaking.getGatherType())) {
                return !spec.isIncorrect() && spec.getQuality() >= breaking.getQuality() && spec.getPower() > 0f;
            }
        }
        return false;
    }

    /** True when a hit of this size takes the block's health to 0 or below (the engine's own test, BlockHealth.isDestroyed). */
    static boolean wouldBreak(float healthNow, float damage) {
        float after = healthNow - damage;
        return Math.abs(after) < 1.0e-5f || after < 0f;
    }
}
