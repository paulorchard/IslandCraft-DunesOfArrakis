/**
 * The ore-wear rule, hooked into the engine's block events. Only blocks listed in {@link OreBreakRules} in worlds generated by
 * Dunes_of_Arrakis are looked at; every handler returns at once for anything else.
 *
 * <ul>
 * <li>{@link PlayerDamage}: a survival player's hit that would break the block is turned into a free break (ore out, block stays whole).
 * It acts on the damage event, before any health is taken, so the block never reaches 0 and the engine never starts a break. When the
 * engine cancels a damage event it re-sends the block to the clients itself.</li>
 * <li>{@link PlayerBreak}, {@link PlaceBlock}: a break (the sixth, or any in Creative) or a placement ends the count.</li>
 * <li>{@link OtherDamage}, {@link OtherBreak}, {@link EnvironmentBreak}: anything that is not a player mining the block removes it
 * without a drop.</li>
 * </ul>
 *
 * All of them run last ({@link RootDependency#lastSet()}), so a break or hit that another mod has cancelled (a claimed chunk) has
 * been dropped from the event by then and is neither counted nor given an ore.
 */
final class OreBreakSystems {

    private static final Query<EntityStore> PLAYERS = Archetype.of(PlayerRef.getComponentType());

    /** Test seam: told the health and the damage of every block damage event that reaches the world-level handler. */
    static volatile java.util.function.BiConsumer<Float, Float> damageObserver;

    private OreBreakSystems() {
    }

    private static boolean active(World world, BlockType block) {
        return block != null && OreBreakRules.isListed(block.getId()) && OreBreakRules.appliesTo(world);
    }

    // ---- the player mining ----

    static final class PlayerDamage extends EntityEventSystem<EntityStore, DamageBlockEvent> {

        PlayerDamage() {
            super(DamageBlockEvent.class);
        }

        @Override
        public Query<EntityStore> getQuery() {
            return PLAYERS;
        }

        @Override
        public Set<Dependency<EntityStore>> getDependencies() {
            return RootDependency.lastSet();
        }

        @Override
        public void handle(int index, ArchetypeChunk<EntityStore> chunk, Store<EntityStore> store, CommandBuffer<EntityStore> buffer,
                DamageBlockEvent event) {
            damageByPlayer(store.getExternalData().getWorld(), buffer, chunk.getComponent(index, Player.getComponentType()), chunk.getReferenceTo(index), event);
        }
    }

    /**
     * A survival player's hit on a listed block: when it would break the block and the block still has free breaks, the damage is cancelled
     * and zeroed and one ore pops out of the face the player looks at. {@code ref} may be null (no look: the ore pops out above the block).
     */
    static void damageByPlayer(World world, ComponentAccessor<EntityStore> accessor, Player player, Ref<EntityStore> ref, DamageBlockEvent event) {
        if (!active(world, event.getBlockType()) || player == null || player.getGameMode() == GameMode.Creative) {
            return;
        }
        Vector3i pos = event.getTargetBlock();
        Vector3d popAt = null;
        Vector3d push = null;
        if (ref != null) {
            try {
                Transform look = TargetUtil.getLook(ref, accessor);
                OreFace.Entry entry = OreFace.entry(look.getPosition(), new Vector3d(look.getDirection()).normalize(), pos);
                popAt = OreFace.offFace(entry, 0.15);
                push = new Vector3d(entry.normal().x * 1.5, 1.5, entry.normal().z * 1.5);
            } catch (RuntimeException e) {
                // no look available: the ore pops out above the block
            }
        }
        if (OreBreakCore.freeBreak(world, accessor, pos, event.getBlockType(), event.getItemInHand(), event.getCurrentDamage(), event.getDamage(), popAt, push)) {
            event.setCancelled(true);
            event.setDamage(0.0f);
        }
    }

    /** A break that goes through (the sixth, or Creative) ends the count; one another system cancels later leaves it. */
    static final class PlayerBreak extends EntityEventSystem<EntityStore, BreakBlockEvent> {

        PlayerBreak() {
            super(BreakBlockEvent.class);
        }

        @Override
        public Query<EntityStore> getQuery() {
            return PLAYERS;
        }

        @Override
        public Set<Dependency<EntityStore>> getDependencies() {
            return RootDependency.lastSet();
        }

        @Override
        public void handle(int index, ArchetypeChunk<EntityStore> chunk, Store<EntityStore> store, CommandBuffer<EntityStore> buffer,
                BreakBlockEvent event) {
            breakByPlayer(store.getExternalData().getWorld(), event);
        }
    }

    /** A break by a player (the sixth, or any in Creative): the count goes once the block is really gone. */
    static void breakByPlayer(World world, BreakBlockEvent event) {
        if (!active(world, event.getBlockType())) {
            return;
        }
        Vector3i pos = new Vector3i(event.getTargetBlock());
        world.execute(() -> OreBreakCounts.forgetIfGone(world, pos.x, pos.y, pos.z));
    }

    static final class PlaceBlock extends EntityEventSystem<EntityStore, PlaceBlockEvent> {

        PlaceBlock() {
            super(PlaceBlockEvent.class);
        }

        @Override
        public Query<EntityStore> getQuery() {
            return PLAYERS;
        }

        @Override
        public void handle(int index, ArchetypeChunk<EntityStore> chunk, Store<EntityStore> store, CommandBuffer<EntityStore> buffer,
                PlaceBlockEvent event) {
            placeByPlayer(store.getExternalData().getWorld(), event);
        }
    }

    /** A block placed where a count was: the count goes, whatever is placed. */
    static void placeByPlayer(World world, PlaceBlockEvent event) {
        if (OreBreakRules.appliesTo(world)) {
            Vector3i pos = event.getTargetBlock();
            OreBreakCounts.forget(world, pos.x, pos.y, pos.z);
        }
    }

    // ---- everything else that removes the block ----

    /** What a hit that is not a player mining does to a listed block: if it would break it, the block goes without a drop. */
    private static void otherDamage(World world, DamageBlockEvent event) {
        java.util.function.BiConsumer<Float, Float> watcher = damageObserver;
        if (watcher != null) {
            watcher.accept(event.getCurrentDamage(), event.getDamage());
        }
        if (!active(world, event.getBlockType()) || !OreBreakRules.wouldBreak(event.getCurrentDamage(), event.getDamage())) {
            return;
        }
        event.setCancelled(true);
        event.setDamage(0.0f);
        OreBreakCore.removeQuietly(world, event.getTargetBlock());
    }

    static final class OtherDamage extends EntityEventSystem<EntityStore, DamageBlockEvent> {

        private static final Query<EntityStore> NOT_PLAYERS = Query.not(PLAYERS);

        OtherDamage() {
            super(DamageBlockEvent.class);
        }

        @Override
        public Query<EntityStore> getQuery() {
            return NOT_PLAYERS;
        }

        @Override
        public Set<Dependency<EntityStore>> getDependencies() {
            return RootDependency.lastSet();
        }

        @Override
        public void handle(int index, ArchetypeChunk<EntityStore> chunk, Store<EntityStore> store, CommandBuffer<EntityStore> buffer,
                DamageBlockEvent event) {
            otherDamage(store.getExternalData().getWorld(), event);
        }
    }

    /** Damage with no actor at all (an explosion, a script). */
    static final class WorldDamage extends WorldEventSystem<EntityStore, DamageBlockEvent> {

        WorldDamage() {
            super(DamageBlockEvent.class);
        }

        @Override
        public Set<Dependency<EntityStore>> getDependencies() {
            return RootDependency.lastSet();
        }

        @Override
        public void handle(Store<EntityStore> store, CommandBuffer<EntityStore> buffer, DamageBlockEvent event) {
            otherDamage(store.getExternalData().getWorld(), event);
        }
    }

    static final class OtherBreak extends EntityEventSystem<EntityStore, BreakBlockEvent> {

        private static final Query<EntityStore> NOT_PLAYERS = Query.not(PLAYERS);

        OtherBreak() {
            super(BreakBlockEvent.class);
        }

        @Override
        public Query<EntityStore> getQuery() {
            return NOT_PLAYERS;
        }

        @Override
        public Set<Dependency<EntityStore>> getDependencies() {
            return RootDependency.lastSet();
        }

        @Override
        public void handle(int index, ArchetypeChunk<EntityStore> chunk, Store<EntityStore> store, CommandBuffer<EntityStore> buffer,
                BreakBlockEvent event) {
            World world = store.getExternalData().getWorld();
            if (active(world, event.getBlockType())) {
                event.setCancelled(true);
                OreBreakCore.removeQuietly(world, event.getTargetBlock());
            }
        }
    }

    /** A break with no actor. The event cannot be cancelled, so the drops are caught as they appear ({@link DropFilter}). */
    static final class EnvironmentBreak extends WorldEventSystem<EntityStore, EnvironmentBreakBlockEvent> {

        EnvironmentBreak() {
            super(EnvironmentBreakBlockEvent.class);
        }

        @Override
        public Set<Dependency<EntityStore>> getDependencies() {
            return RootDependency.lastSet();
        }

        @Override
        public void handle(Store<EntityStore> store, CommandBuffer<EntityStore> buffer, EnvironmentBreakBlockEvent event) {
            World world = store.getExternalData().getWorld();
            if (!active(world, event.getBlockType())) {
                return;
            }
            Vector3i pos = new Vector3i(event.getTargetBlock());
            DropFilter.expect(pos, event.getBlockType());
            world.execute(() -> OreBreakCounts.forgetIfGone(world, pos.x, pos.y, pos.z));
        }
    }

    /** Removes the items that a break with no actor spawns at the block: the ore and the rock that block would drop. */
    static final class DropFilter extends RefSystem<EntityStore> {

        private static final long LIFETIME_NANOS = 1_000_000_000L;

        private record Expected(Vector3d center, Set<String> items, long until) {
        }

        private static final List<Expected> EXPECTED = new ArrayList<>();

        static void expect(Vector3i pos, BlockType block) {
            Set<String> items = new java.util.HashSet<>();
            for (ItemStack stack : OreBreakCore.dropsOf(block)) {
                items.add(stack.getItemId());
            }
            synchronized (EXPECTED) {
                long now = System.nanoTime();
                EXPECTED.removeIf(e -> e.until() < now);
                EXPECTED.add(new Expected(new Vector3d(pos.x + 0.5, pos.y + 0.5, pos.z + 0.5), items, now + LIFETIME_NANOS));
            }
        }

        @Override
        public Query<EntityStore> getQuery() {
            return Archetype.of(ItemComponent.getComponentType(), TransformComponent.getComponentType());
        }

        @Override
        public void onEntityAdded(Ref<EntityStore> ref, AddReason reason, Store<EntityStore> store, CommandBuffer<EntityStore> buffer) {
            synchronized (EXPECTED) {
                if (EXPECTED.isEmpty()) {
                    return;
                }
                ItemComponent item = store.getComponent(ref, ItemComponent.getComponentType());
                TransformComponent where = store.getComponent(ref, TransformComponent.getComponentType());
                if (item == null || where == null || item.getItemStack() == null) {
                    return;
                }
                String id = item.getItemStack().getItemId();
                long now = System.nanoTime();
                for (Expected e : EXPECTED) {
                    if (e.until() >= now && e.items().contains(id) && e.center().distance(where.getPosition()) < 1.6) {
                        buffer.removeEntity(ref, RemoveReason.REMOVE);
                        return;
                    }
                }
            }
        }

        @Override
        public void onEntityRemove(Ref<EntityStore> ref, RemoveReason reason, Store<EntityStore> store, CommandBuffer<EntityStore> buffer) {
        }
    }

    // ---- the saved counts ----

    /** When a section with counts loads, drops the entries whose block is no longer there (replaced while the section was away). */
    static final class SectionSweep extends RefSystem<ChunkStore> {

        @Override
        public Query<ChunkStore> getQuery() {
            return Archetype.of(OreBreakCounts.type());
        }

        @Override
        public void onEntityAdded(Ref<ChunkStore> ref, AddReason reason, Store<ChunkStore> store, CommandBuffer<ChunkStore> buffer) {
            OreBreakCounts.sweep(store, ref);
        }

        @Override
        public void onEntityRemove(Ref<ChunkStore> ref, RemoveReason reason, Store<ChunkStore> store, CommandBuffer<ChunkStore> buffer) {
        }
    }
}
